function at(offsetDays, hour = 18, minute = 0) {
  const base = new Date()
  base.setHours(hour, minute, 0, 0)
  base.setDate(base.getDate() + offsetDays)
  return base.toISOString()
}

function item(system, index, row) {
  const subtitle = row.subtitle || ''
  return {
    id: `${system}-demo-${index}`,
    system,
    subtitle: '',
    owner: '',
    status: 'unfinished',
    statusLabel: '进行中',
    dueSource: 'field',
    ...row,
    project: row.project || subtitle.split(' · ')[0] || '未标注项目',
  }
}

